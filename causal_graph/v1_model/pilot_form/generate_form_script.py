"""Generate the pilot form's Apps Script and its import mapping from the live item banks.

    python -m causal_graph.v1_model.pilot_form.generate_form_script            # write both
    python -m causal_graph.v1_model.pilot_form.generate_form_script --check    # exit 1 if stale

Writes, next to this file:

    build_form.gs       Google Apps Script (FormApp). Paste into script.google.com, run
                        `buildPilotForm` once, and it creates the form. Pure ASCII: every
                        string is emitted as a JSON literal, so curly quotes and dashes travel
                        as \\u escapes and survive any copy-paste.
    form_mapping.json   What the importer reads: one entry per response-sheet column, in
                        column order, with the item it answers and option text -> stored
                        answer. Also pure ASCII.

Both are committed. tests/test_pilot_form.py regenerates them in memory and fails if the
committed copies differ -- the form cannot drift from the banks without a red test.

No Google API is called. Nothing here touches a network or a database.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from . import PACKAGE_DIR
from .spec import SUBMIT, FormSpec, _norm, build_spec

SCRIPT_PATH = Path(PACKAGE_DIR) / "build_form.gs"
MAPPING_PATH = Path(PACKAGE_DIR) / "form_mapping.json"

#: The first column of every Google Forms response export.
TIMESTAMP_COLUMN = "Timestamp"


def _js(value) -> str:
    """A JavaScript literal for a str/int/bool/None -- JSON is valid JS, and
    ensure_ascii keeps the file ASCII."""
    return json.dumps(value, ensure_ascii=True)


def _var(page_id: str) -> str:
    return "page_" + page_id


def render_mapping(spec: FormSpec) -> str:
    seen: dict = {}
    columns = []
    for q in spec.questions():
        key = _norm(q.title)
        seen[key] = seen.get(key, 0) + 1
        columns.append(
            {
                "qid": q.qid,
                "title": q.title,
                "occurrence": seen[key],
                "role": q.role,
                "item_id": q.item_id,
                "slot": q.slot,
                "required": q.required,
                "answers": [[c.text, c.answer] for c in q.choices],
            }
        )
    doc = {
        "_generated_by": "causal_graph/v1_model/pilot_form/generate_form_script.py -- do not edit",
        "pilot_form_version": spec.pilot_form_version,
        "core_form_version": spec.core_form_version,
        "env_form_version": spec.env_form_version,
        "core_item_order": list(spec.core_item_order),
        "timestamp_column": TIMESTAMP_COLUMN,
        "columns": columns,
    }
    return json.dumps(doc, indent=2, ensure_ascii=True) + "\n"


def render_script(spec: FormSpec) -> str:
    pages = list(spec.pages)
    page_ids = [p.page_id for p in pages]
    for index, page in enumerate(pages):
        if page.go_to is not None and index == len(pages) - 1:
            raise ValueError("the last page cannot carry a go_to")

    out = []
    w = out.append
    w("// GENERATED by causal_graph/v1_model/pilot_form/generate_form_script.py -- do not edit.")
    w("// %s | core %s | env %s" % (spec.pilot_form_version, spec.core_form_version,
                                     spec.env_form_version))
    w("//")
    w("// How to use: script.google.com -> New project -> replace everything with this file ->")
    w("// Save -> choose buildPilotForm -> Run -> allow access to Google Forms. The log prints")
    w("// the form's edit link and its share link. Run it ONCE; each run makes a new form.")
    w("// See causal_graph/v1_model/pilot_form/README.md.")
    w("")
    w("function buildPilotForm() {")
    w("  var form = FormApp.create(%s);" % _js(spec.title))
    w("  form.setDescription(%s);" % _js(spec.description))
    w("  form.setConfirmationMessage(%s);" % _js(spec.confirmation))
    w("  // Google's automatic email collection stays OFF: the only email is the optional")
    w("  // question on the last page, so answers are never tied to an address by default.")
    w("  try { form.setEmailCollectionType(FormApp.EmailCollectionType.DO_NOT_COLLECT); }")
    w("  catch (e) { form.setCollectEmail(false); }")
    w("  // Question order is fixed (the core order is the app's interleaved order).")
    w("  form.setShuffleQuestions(false);")
    w("  form.setProgressBar(true);")
    w("  form.setAllowResponseEdits(false);")
    w("  form.setPublishingSummary(false);")
    w("  form.setShowLinkToRespondAgain(false);")
    w("")
    w("  var pages = {};")
    w("  var branching = {};")
    w("  var item;")
    w("")
    for page in pages:
        w("  // ---- page %s" % page.page_id)
        w("  pages[%s] = form.addPageBreakItem().setTitle(%s)%s;" % (
            _js(page.page_id), _js(page.title),
            ".setHelpText(%s)" % _js(page.description) if page.description else ""))
        for q in page.questions:
            if q.kind == "email":
                w("  item = form.addTextItem().setTitle(%s).setRequired(%s);"
                  % (_js(q.title), _js(q.required)))
                if q.help_text:
                    w("  item.setHelpText(%s);" % _js(q.help_text))
                w("  item.setValidation(FormApp.createTextValidation()"
                  ".setHelpText(\"Please enter an email address, or leave this blank.\")"
                  ".requireTextIsEmail().build());")
                continue
            w("  item = form.addMultipleChoiceItem().setTitle(%s).setRequired(%s);"
              % (_js(q.title), _js(q.required)))
            if q.help_text:
                w("  item.setHelpText(%s);" % _js(q.help_text))
            if any(c.go_to for c in q.choices):
                # Choices that navigate are set in the second pass, once every page exists.
                w("  branching[%s] = item;" % _js(q.qid))
                continue
            w("  item.setChoiceValues([")
            for c in q.choices:
                w("    %s," % _js(c.text))
            w("  ]);")
        w("")

    w("  // ---- second pass: branching choices and end-of-section jumps")
    for page in pages:
        for q in page.questions:
            if not any(c.go_to for c in q.choices):
                continue
            w("  item = branching[%s];" % _js(q.qid))
            w("  item.setChoices([")
            for c in q.choices:
                target = ("FormApp.PageNavigationType.SUBMIT" if c.go_to == SUBMIT
                          else "pages[%s]" % _js(c.go_to))
                w("    item.createChoice(%s, %s)," % (_js(c.text), target))
            w("  ]);")
    for index, page in enumerate(pages):
        if page.go_to is None:
            continue
        # PageBreakItem.setGoToPage acts on the page BEFORE the break: "the page to jump to
        # after completing the page before this page break". So the jump after `page` is
        # set on the break that starts the NEXT page.
        following = page_ids[index + 1]
        target = ("FormApp.PageNavigationType.SUBMIT" if page.go_to == SUBMIT
                  else "pages[%s]" % _js(page.go_to))
        method = "setGoToPage"
        w("  // after %s, go to %s" % (page.page_id, page.go_to))
        w("  pages[%s].%s(%s);" % (_js(following), method, target))
    w("")
    w("  Logger.log('Edit link:  ' + form.getEditUrl());")
    w("  Logger.log('Share link: ' + form.getPublishedUrl());")
    w("}")
    return "\n".join(out) + "\n"


def render_all() -> tuple[str, str]:
    spec = build_spec()
    return render_script(spec), render_mapping(spec)


def _read(path: Path) -> str:
    return path.read_text(encoding="ascii") if path.exists() else ""


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--check", action="store_true",
                        help="do not write; exit 1 if the committed files are stale")
    args = parser.parse_args(argv)

    script, mapping = render_all()
    stale = [p.name for p, text in ((SCRIPT_PATH, script), (MAPPING_PATH, mapping))
             if _read(p) != text]

    if args.check:
        if stale:
            print("STALE: %s -- regenerate with "
                  "python -m causal_graph.v1_model.pilot_form.generate_form_script"
                  % ", ".join(stale))
            return 1
        print("pilot form files are up to date")
        return 0

    # newline="\n": the committed bytes must not depend on the OS that generated them.
    SCRIPT_PATH.write_text(script, encoding="ascii", newline="\n")
    MAPPING_PATH.write_text(mapping, encoding="ascii", newline="\n")
    print("wrote %s and %s (%s)" % (SCRIPT_PATH.name, MAPPING_PATH.name,
                                     "changed: " + ", ".join(stale) if stale else "unchanged"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
