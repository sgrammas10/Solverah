"""Write N synthetic people into a local solverah_modeldev database, with a
planted truth, so the fit has something to recover.

    SOLVERAH_IGNORE_DOTENV=1 APP_ENV=testing \\
    DATABASE_URL=postgresql://solverah:solverah@localhost:5433/solverah_modeldev \\
    JWT_SECRET_KEY=... \\
    python -m causal_graph.v1_model.devfit.seed_synthetic --n 1200 --seed 0

EVERYTHING GOES THROUGH THE SANCTIONED STORE FUNCTIONS
------------------------------------------------------
No raw SQL against the sealed person-side profile, and none of its table names
appear anywhere in this file -- decision D-01, enforced by
tests/test_employer_visibility.py, which walks every .py file in the repo and
reads string literals and docstrings as well as identifiers. The doorways used
here are the same ones the app uses:

    users               the ORM User model (as tests/conftest.py's seed_user does)
    core sitting        assessment_store.persist_submission(db, user_id, ScoredSubmission)
    environment report  environment_report_store.write_environment_report(...)
                        with dimension_scores from work_pulse.situation.score_environment

Neither store function commits; this script owns the transaction and commits in
batches.

MARKING, AND WHY IT IS A RULE RATHER THAN A CONVENTION
-------------------------------------------------------
Every synthetic user's email ends in `@synthetic.solverah.invalid` -- `.invalid`
is reserved by RFC 2606 and can never resolve, so one of these addresses cannot
be mailed even by accident. The script REFUSES to seed a database that already
holds a user whose email does not end that way, and `--reset` deletes only rows
belonging to synthetic users. Combined with the guard, that is two independent
reasons a real database cannot be touched: the URL is refused, and even a
correctly-named database that somehow held real users is refused.

THE PLANTED TRUTH
-----------------
Ratings are drawn from the model's OWN predictor -- `match_core.outcome_logit`
under true weights, then `match_core.ordinal_probs` -- rather than from a
re-derivation of the formula here. That is deliberate: the gap convention
(person snapped onto COMPANY_LATTICE, `g = person - env`) is easy to get subtly
backwards, and calling the real function is the only way to be sure the data a
fit sees was generated by the model the fit assumes.

True weights are the live priors' means with TWO deviations, chosen so a
successful fit is visible rather than a matter of decimal places:

    autonomy mag  -3.0   (the expert put it at -0.67 -- the mildest dimension)
    pace     mag  -0.5   (the expert put it at -2.52 -- the costliest)

They are nearly swapped. If the fit recovers them, the posterior has to move a
long way against a confident prior, and `explain_user` should reorder those two
dimensions for a user whose autonomy and pace gaps are comparable.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

from . import MODEL_DIR, REPO_ROOT  # noqa: F401  -- sys.path side effects
from .guard import add_database_argument, require_database_url

import numpy as np

SYNTHETIC_EMAIL_DOMAIN = "@synthetic.solverah.invalid"

DIMS = ("autonomy", "pace", "collaboration", "feedback", "innovation", "decision")

#: Planted deviations from the live priors' means. Everything else is the
#: expert's own number, so the fit is being asked to move two weights and leave
#: sixteen alone -- a sharper test than perturbing all of them.
PLANTED_MAG = {"autonomy": -3.0, "pace": -0.5}

#: The generating cutpoints. The rating-3/4 boundary is 0 because that pin is
#: what makes sigmoid(z) mean P(rating >= 4); the other three are the prior's
#: central spacing of 1.5.
TRUE_CUTPOINTS = np.array([-3.0, -1.5, 0.0, 1.5])

#: Fraction of (user, dimension) cells where the environment is drawn NEAR the
#: person's own answer instead of independently. Real people self-select into
#: jobs, so fully independent draws would put almost nobody near a small gap and
#: the top rating would be too rare to train on. Not a thumb on the scale for
#: any particular weight: it widens coverage of the gap range symmetrically.
DEFAULT_ALIGNED_RATE = 0.45

#: Share of environment reports whose `comp` is the instrument's real "not sure"
#: option -- a documented NULL (PRODUCT_DECISIONS.md section 2), carried as NaN
#: plus a mask and excluded from the linear predictor for that row.
DEFAULT_COMP_UNSURE_RATE = 0.15

#: Career statuses the assembler will train on. `first_job` is excluded by
#: design: the route refuses it with a 409 and the assembler drops it.
CAREER_STATUSES = ("employed", "between_jobs")

#: Where the generating truth is written. OUTSIDE the repo, next to the
#: verification venv, so a fit report can be compared against it without the
#: file ever becoming a tracked artifact that drifts from the run that made it.
DEFAULT_TRUTH_PATH = (
    Path(REPO_ROOT).parent / "solverah-devfit" / "last_truth.json"
)


# ---------------------------------------------------------------------------
# Person side: choose option keys that land each dimension on a target score
# ---------------------------------------------------------------------------
def _person_items_by_dimension(items_index):
    """{dimension: [(item_id, high_key, low_key), ...]} from the real item file.

    The instrument scores `mean_pole` over four binary-pole items per dimension,
    so a dimension's score is (# high-pole options chosen) / 4 -- exactly
    PERSON_LATTICE. Reading the poles from the file rather than hardcoding option
    positions is what keeps this correct if the item bank is reordered.
    """
    by_dim: dict = {}
    for item in items_index["by_id"].values():
        keys = {opt["pole"]: opt["key"] for opt in item["options"]}
        if set(keys) != {"high", "low"}:
            raise SystemExit(
                "item %s does not have exactly one high and one low option -- this "
                "seeder assumes the binary-pole instrument" % item["id"]
            )
        by_dim.setdefault(item["dimension"], []).append(
            (item["id"], keys["high"], keys["low"])
        )
    for dim, items in by_dim.items():
        items.sort()  # stable, so a given seed always produces the same answers
        if len(items) != 4:
            raise SystemExit(
                "dimension %r has %d items; this seeder's score targeting assumes 4"
                % (dim, len(items))
            )
    return by_dim


def _person_choices(by_dim, targets, rng):
    """{item_id: option_key} landing each dimension on its target score.

    Which of the four items carry the high pole is randomized, so two people with
    the same score do not have identical answer patterns -- the stored raw rows
    are what the assembler re-scores, and a degenerate pattern would also give
    every user the same Guttman error count and therefore the same confidence.
    """
    choices: dict = {}
    for dim, items in by_dim.items():
        n_high = int(round(targets[dim] * len(items)))
        high_positions = set(rng.choice(len(items), size=n_high, replace=False).tolist())
        for position, (item_id, high_key, low_key) in enumerate(items):
            choices[item_id] = high_key if position in high_positions else low_key
    return choices


# ---------------------------------------------------------------------------
# Environment side: choose poles that land each dimension near a target
# ---------------------------------------------------------------------------
def _env_items_by_dimension(situation_items):
    by_dim: dict = {}
    for item in situation_items.ENVIRONMENT_ITEMS:
        by_dim.setdefault(item["dimension"], []).append(item)
    for dim, items in by_dim.items():
        items.sort(key=lambda i: i["item_id"])
    return by_dim


def _env_answers(env_by_dim, situation_items, targets, rng):
    """{item_id: option_key} whose per-dimension mean is as near `targets` as the
    two-item ladder allows.

    An environment score is the mean of that dimension's two items' pole values,
    drawn from {0.1, 0.3, 0.5, 0.7, 0.9} -- so the reachable means are
    0.1, 0.2, ... 0.9. The pair is picked by exhaustive search over that tiny
    grid rather than by arithmetic, with ties broken randomly so the same target
    does not always produce the same pair.
    """
    pole_values = situation_items.POLE_VALUES
    answers: dict = {}
    for dim, items in env_by_dim.items():
        target = targets[dim]
        best_error = None
        candidates: list = []
        for pole_a, value_a in pole_values.items():
            for pole_b, value_b in pole_values.items():
                error = round(abs((value_a + value_b) / 2.0 - target), 6)
                if best_error is None or error < best_error:
                    best_error, candidates = error, [(pole_a, pole_b)]
                elif error == best_error:
                    candidates.append((pole_a, pole_b))
        pole_a, pole_b = candidates[int(rng.integers(len(candidates)))]
        for item, pole in zip(items, (pole_a, pole_b)):
            answers[item["item_id"]] = next(
                opt["key"] for opt in item["options"] if opt["pole"] == pole
            )
    return answers


# ---------------------------------------------------------------------------
# The truth
# ---------------------------------------------------------------------------
def true_weights(cfg, pri):
    """The live priors' means, with PLANTED_MAG substituted. Point weights (plain
    floats), the shape `outcome_logit` wants."""
    import match_core

    weights = match_core.point_weights(match_core.weights_from_priors(cfg, pri))
    for dim, mag in PLANTED_MAG.items():
        weights["dimensions"][dim]["mag"] = mag
    return weights


def _truth_record(cfg, pri, *, n, seed, aligned_rate, comp_unsure_rate, database):
    weights = true_weights(cfg, pri)
    return {
        "n": int(n),
        "seed": int(seed),
        "database": database.rsplit("/", 1)[-1],
        "aligned_rate": float(aligned_rate),
        "comp_unsure_rate": float(comp_unsure_rate),
        "cutpoints": TRUE_CUTPOINTS.tolist(),
        "intercept": float(weights["intercept"]),
        "planted": {("%s_mag" % dim): float(mag) for dim, mag in PLANTED_MAG.items()},
        "dimensions": {
            dim: {feat: float(value) for feat, value in feats.items()}
            for dim, feats in weights["dimensions"].items()
        },
        "confounders": {
            "stage_size": float(weights["confounders"]["stage_size"]),
            "comp": float(weights["confounders"]["comp"]),
            "industry": "never supplied by the instrument -- fully masked, no truth",
        },
    }


# ---------------------------------------------------------------------------
# Reporting
# ---------------------------------------------------------------------------
def _histogram(values, edges, label):
    counts, _ = np.histogram(values, bins=edges)
    total = max(int(counts.sum()), 1)
    lines = ["  %s" % label]
    for i, count in enumerate(counts):
        lines.append(
            "    [%+.2f, %+.2f)  %5d  %5.1f%%  %s"
            % (edges[i], edges[i + 1], count, 100.0 * count / total,
               "#" * int(round(40.0 * count / total)))
        )
    return "\n".join(lines)


def _report_spread(gaps_by_dim, ratings, min_level_share):
    print("")
    print("GAP DISTRIBUTION (g = person - env, the model's own convention)")
    edges = np.linspace(-1.0, 1.0, 11)
    for dim in DIMS:
        print(_histogram(gaps_by_dim[dim], edges, dim))

    print("")
    print("RATING DISTRIBUTION (the outcome the ordinal head trains on)")
    counts = np.bincount(np.asarray(ratings, dtype=int), minlength=6)[1:]
    total = max(int(counts.sum()), 1)
    thin = []
    for level in range(1, 6):
        share = counts[level - 1] / total
        print("    rating %d  %5d  %5.1f%%  %s"
              % (level, counts[level - 1], 100.0 * share, "#" * int(round(60.0 * share))))
        if share < min_level_share:
            thin.append((level, share))
    return thin


# ---------------------------------------------------------------------------
# Seeding
# ---------------------------------------------------------------------------
def _non_synthetic_user_count(User):
    return (
        User.query
        .filter(~User.email.ilike("%" + SYNTHETIC_EMAIL_DOMAIN))
        .count()
    )


def assert_safe_to_seed(User, EnvironmentReport):
    """Raise SystemExit unless this database is one we may write a cohort into.

    The guard in guard.py checks the URL; this checks the CONTENTS, and the two
    are deliberately independent. A database can be named correctly and still
    hold something real -- someone's local scratch copy of production data, say
    -- and a name is not evidence about rows.

    Two refusals:

    * a user whose email is not marked synthetic. This harness only ever writes
      to a database it filled itself.
    * any existing environment report. A second cohort on top of a first would
      train on both while `last_truth.json` described only the newer one, and
      the resulting "recovery" number would be meaningless in a way nothing
      downstream could detect.

    Separated from `seed()` so it is testable without a live seeding run -- it
    is the check most worth having a test, and the hardest to reach through the
    CLI.
    """
    real_users = _non_synthetic_user_count(User)
    if real_users:
        raise SystemExit(
            "refusing to seed: %d user(s) in this database do not end in %s. This "
            "harness only ever writes to a database it filled itself. Use a fresh "
            "solverah_modeldev database." % (real_users, SYNTHETIC_EMAIL_DOMAIN)
        )

    existing_reports = EnvironmentReport.query.count()
    if existing_reports:
        raise SystemExit(
            "refusing to seed: this database already holds %d environment "
            "report(s). A fit would train on both cohorts while last_truth.json "
            "described only the newer one. Run --reset first." % existing_reports
        )


def _reset(db, User):
    """Delete synthetic users' ENVIRONMENT REPORTS -- the training rows, and the
    only thing the assembler reads. Returns the number of reports removed.

    WHAT THIS DELIBERATELY DOES NOT DELETE, and why
    ------------------------------------------------
    The synthetic users themselves, and their core sittings, stay. There is no
    doorway to delete the sealed person-side rows because the product decided
    there should not be one: those rows SURVIVE account deletion de-identified
    (a decided reconciliation, asserted in tests/test_account_lifecycle.py), so
    even `account_service.delete_account` leaves them and tombstones the user row
    instead. Their foreign keys are NO ACTION rather than ON DELETE CASCADE,
    which is that decision expressed in the schema.

    Reaching past that from a dev script would mean writing SQL against tables
    D-01 seals, and no local convenience is worth teaching the codebase that the
    seal is optional. So a reset removes the training rows and says what it left.

    Leftovers are harmless: the assembler builds rows from environment reports,
    so a user with no report contributes nothing. To reclaim the space, drop and
    re-migrate the database -- the recipe is in this package's README.
    """
    from model import EnvironmentDimensionScore, EnvironmentReport

    user_ids = [
        u.id for u in
        User.query.filter(User.email.ilike("%" + SYNTHETIC_EMAIL_DOMAIN)).all()
    ]
    if not user_ids:
        print("reset: no synthetic users in this database")
        return 0

    report_ids = [
        r.id for r in EnvironmentReport.query
        .filter(EnvironmentReport.user_id.in_(user_ids)).all()
    ]
    if report_ids:
        (EnvironmentDimensionScore.query
         .filter(EnvironmentDimensionScore.environment_report_id.in_(report_ids))
         .delete(synchronize_session=False))
        (EnvironmentReport.query
         .filter(EnvironmentReport.id.in_(report_ids))
         .delete(synchronize_session=False))
    db.session.commit()

    print("reset: removed %d environment report(s) from %d synthetic user(s)"
          % (len(report_ids), len(user_ids)))
    print("       the users and their sealed core sittings remain, by D-01 design;")
    print("       they hold no training rows now. Full wipe: see devfit/README.md")
    return len(report_ids)


class SyntheticCohort:
    """Draws synthetic (person, environment, rating) rows. Touches no database.

    Split out from `seed()` so tests can exercise the SAME generation and the
    SAME writer against the test database, rather than a second implementation
    that could drift from the one the real cohort is built with.
    """

    def __init__(self, *, aligned_rate=DEFAULT_ALIGNED_RATE,
                 comp_unsure_rate=DEFAULT_COMP_UNSURE_RATE, cfg=None, pri=None):
        import assessment_form
        import match_core
        from work_pulse import situation, situation_items

        self.match_core = match_core
        self.assessment_form = assessment_form
        self.situation = situation
        self.situation_items = situation_items

        if cfg is None or pri is None:
            cfg, pri = match_core.load()
        self.cfg, self.pri = cfg, pri
        self.weights = true_weights(cfg, pri)
        self.aligned_rate = aligned_rate
        self.comp_unsure_rate = comp_unsure_rate

        self.items_index = assessment_form.load_items(
            Path(assessment_form.DEFAULT_ITEMS_PATH)
        )
        self.person_by_dim = _person_items_by_dimension(self.items_index)
        self.env_by_dim = _env_items_by_dimension(situation_items)
        self.scoring_key = assessment_form.scoring_key_version()

    def draw(self, rng):
        """One person: their answers, their job's answers, and the rating the
        TRUE model gives that pair."""
        match_core = self.match_core
        lattice = match_core.PERSON_LATTICE

        person_targets = {
            dim: float(lattice[rng.integers(len(lattice))]) for dim in DIMS
        }
        env_targets = {}
        for dim in DIMS:
            if rng.random() < self.aligned_rate:
                # Near the person's own answer, with a little slack -- people
                # end up in roles that roughly suit them.
                env_targets[dim] = float(
                    np.clip(person_targets[dim] + rng.normal(0.0, 0.12), 0.1, 0.9)
                )
            else:
                env_targets[dim] = float(rng.uniform(0.1, 0.9))

        choices = _person_choices(self.person_by_dim, person_targets, rng)
        answers = _env_answers(self.env_by_dim, self.situation_items, env_targets, rng)

        person_scores = self.assessment_form.score_stored_choices(choices)
        career_status = CAREER_STATUSES[int(rng.integers(len(CAREER_STATUSES)))]
        env_scores = self.situation.score_environment(
            answers, self.situation_items.item_spec(career_status)
        )

        stage_size = int(rng.integers(1, 6))
        comp = None if rng.random() < self.comp_unsure_rate else int(rng.integers(1, 6))

        # The rating comes from the model's OWN predictor, not a copy of it --
        # the gap convention (person snapped, g = person - env) is exactly the
        # thing a re-derivation gets subtly wrong.
        conf_raw = {
            "stage_size": [float(stage_size)],
            "comp": [np.nan if comp is None else float(comp)],
            "industry": [None],
        }
        conf_missing = {
            "stage_size": np.array([False]),
            "comp": np.array([comp is None]),
            "industry": np.array([True]),   # the instrument never asks it
        }
        conf = match_core.preprocess_conf(conf_raw, self.cfg, conf_missing=conf_missing)
        z = float(np.asarray(match_core.outcome_logit(
            {dim: np.array([person_scores[dim]]) for dim in DIMS},
            {dim: np.array([env_scores[dim]]) for dim in DIMS},
            conf, self.cfg, self.weights,
        ))[0])
        probs = match_core.ordinal_probs(z, TRUE_CUTPOINTS)

        return {
            "choices": choices,
            "answers": answers,
            "person_scores": person_scores,
            "env_scores": env_scores,
            "career_status": career_status,
            "stage_size": stage_size,
            "comp": comp,
            "z": z,
            "rating": int(rng.choice(5, p=probs / probs.sum()) + 1),
            "gaps": {
                dim: float(match_core.closest_achievable(person_scores[dim]))
                - env_scores[dim]
                for dim in DIMS
            },
        }

    def write(self, db, email, row):
        """Write one drawn row through the sanctioned store functions. Does not
        commit -- the caller owns the transaction, same as the stores do."""
        import assessment_store
        import environment_report_store
        from model import User

        user = User(email=email, password_hash="not-a-real-hash")
        db.session.add(user)
        db.session.flush()

        assessment_store.persist_submission(
            db,
            user.id,
            self.assessment_form.ScoredSubmission(
                form_version=self.items_index["form_version"],
                scoring_key_version=self.scoring_key,
                scores=row["person_scores"],
                choices=row["choices"],
                confidences=_confidences(
                    self.assessment_form, row["choices"], self.items_index
                ),
            ),
        )
        environment_report_store.write_environment_report(
            db,
            user.id,
            raw_answers=row["answers"],
            dimension_scores=row["env_scores"],
            stage_size=row["stage_size"],
            comp=row["comp"],
            experienced_outcome=row["rating"],
            career_status=row["career_status"],
            version=self.situation_items.FORM_VERSION,
        )
        return user.id


def seed(url, *, n, seed_value, aligned_rate, comp_unsure_rate, min_level_share,
         truth_path, batch_size=100):
    os.environ["DATABASE_URL"] = url

    from app import app
    from model import User, db

    cohort = SyntheticCohort(
        aligned_rate=aligned_rate, comp_unsure_rate=comp_unsure_rate
    )
    cfg, pri = cohort.cfg, cohort.pri
    rng = np.random.default_rng(seed_value)

    with app.app_context():
        from model import EnvironmentReport
        assert_safe_to_seed(User, EnvironmentReport)

        # A --reset leaves earlier cohorts' users behind (see _reset), and the
        # email index has to stay unique across runs. Offsetting by how many are
        # already there keeps the numbering stable within a run without a random
        # tag, so the same --seed still produces the same PEOPLE -- only the
        # label differs.
        email_offset = User.query.filter(
            User.email.ilike("%" + SYNTHETIC_EMAIL_DOMAIN)
        ).count()
        if email_offset:
            print("note: %d synthetic user(s) from an earlier cohort are present "
                  "with no training rows; numbering this cohort from %d"
                  % (email_offset, email_offset))

        gaps_by_dim = {dim: [] for dim in DIMS}
        ratings: list = []
        written = 0

        for index in range(n):
            row = cohort.draw(rng)
            ratings.append(row["rating"])
            for dim in DIMS:
                gaps_by_dim[dim].append(row["gaps"][dim])

            cohort.write(
                db,
                "synth-%05d%s" % (email_offset + index, SYNTHETIC_EMAIL_DOMAIN),
                row,
            )

            written += 1
            if written % batch_size == 0:
                db.session.commit()
                print("  seeded %d / %d" % (written, n))

        db.session.commit()

    print("")
    print("seeded %d synthetic users into %s" % (written, url.rsplit("/", 1)[-1]))
    thin = _report_spread(gaps_by_dim, ratings, min_level_share)

    truth = _truth_record(
        cfg, pri, n=written, seed=seed_value, aligned_rate=aligned_rate,
        comp_unsure_rate=comp_unsure_rate, database=url,
    )
    truth_path = Path(truth_path)
    truth_path.parent.mkdir(parents=True, exist_ok=True)
    truth_path.write_text(json.dumps(truth, indent=2), encoding="ascii")
    print("")
    print("truth written to %s" % truth_path)

    if thin:
        print("")
        print("STOP: rating level(s) below the %.0f%% floor: %s"
              % (100.0 * min_level_share,
                 ", ".join("%d at %.1f%%" % (lvl, 100.0 * s) for lvl, s in thin)))
        print("A level the data barely contains cannot train its own cutpoint.")
        print("Raise --n, or --aligned-rate for more high ratings / less for more low.")
        return 1
    return 0


def _confidences(assessment_form, choices, items_index):
    """Per-dimension stored confidence, derived the same way submit_form derives
    it -- D-17, with feedback left None (D-17(a))."""
    errors = assessment_form.error_counts_all_dimensions(choices, items_index)
    return {
        dim: (None if dim in assessment_form.CONFIDENCE_PENDING_DIMENSIONS
              else assessment_form.confidence_from_error(e))
        for dim, e in errors.items()
    }


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Seed synthetic people with a planted truth into solverah_modeldev."
    )
    add_database_argument(parser)
    parser.add_argument("--n", type=int, default=1200,
                        help="how many synthetic people to write (default 1200)")
    parser.add_argument("--seed", type=int, default=0,
                        help="RNG seed; a given seed always writes the same cohort")
    parser.add_argument("--aligned-rate", type=float, default=DEFAULT_ALIGNED_RATE,
                        help="share of (person, dimension) cells whose environment is "
                             "drawn near the person's own answer (default %.2f)"
                             % DEFAULT_ALIGNED_RATE)
    parser.add_argument("--comp-unsure-rate", type=float,
                        default=DEFAULT_COMP_UNSURE_RATE,
                        help="share of reports answering comp with 'not sure'")
    parser.add_argument("--min-level-share", type=float, default=0.02,
                        help="stop if any rating level holds less than this share")
    parser.add_argument("--truth-out", default=str(DEFAULT_TRUTH_PATH),
                        help="where to write the generating truth (default: outside "
                             "the repo, at %s)" % DEFAULT_TRUTH_PATH)
    parser.add_argument("--reset", action="store_true",
                        help="delete every synthetic user's rows, then exit")
    args = parser.parse_args(argv)

    url = require_database_url(args.database_url)

    if args.reset:
        os.environ["DATABASE_URL"] = url
        from app import app
        from model import User, db
        with app.app_context():
            _reset(db, User)
        return 0

    return seed(
        url,
        n=args.n,
        seed_value=args.seed,
        aligned_rate=args.aligned_rate,
        comp_unsure_rate=args.comp_unsure_rate,
        min_level_share=args.min_level_share,
        truth_path=args.truth_out,
    )


