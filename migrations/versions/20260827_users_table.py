"""Phase 2c: `user` becomes `users`, with the Part 4.2 identity columns.

Storage change only. Every field whose shape moves here is adapted before it
reaches a response, so `GET /me`, `GET /auth/session` and `GET /me/profile`
return the same bytes they returned before -- captured and diffed with
`Scripts/capture_contract.py` / `Scripts/verify_contract.py`.

Five decisions are baked into this file.

**`user_role`'s values are hyphenated.**  Part 4.2 writes the enum as
`('job_seeker','recruiter','admin')`.  The value that is stored, transmitted, and
gated on today is `job-seeker`, and `src/App.tsx` gates fifteen routes on
`allowedRoles={["job-seeker"]}`.  An underscored enum would make every protected
route reject every user, so the enum takes the spelling the system already uses.
Changing the spelling is a wire change and belongs with the frontend, not here.

**`GENERATED BY DEFAULT AS IDENTITY`, not `ALWAYS`.**  Part 4.1 says `ALWAYS`, and
`ALWAYS` rejects an explicit id without `OVERRIDING SYSTEM VALUE`.
`tests/conftest.py::seed_user` inserts `User(id=user_id, ...)` on purpose --
several tests assert behaviour about a *specific* user id.  `BY DEFAULT` keeps
that fixture ORM-shaped and costs nothing in production, where no code path
supplies an id.  The identity column is still the point: the sequence is the
database's, not the application's.

**`email_normalized` is not created.**  Part 4.2 declares it for dedupe with
dot/plus folding.  Folding dots is correct for Gmail and wrong for most other
providers -- dots are significant at Fastmail, at Proton, and in most corporate
domains -- so a global fold would refuse legitimate signups by declaring
`a.b@fastmail.com` a duplicate of `ab@fastmail.com`.  Scoping the fold to the
domains where it holds is a product rule with a list to maintain, and it belongs
with the signup flow rather than inside a table rename.  `email` becoming CITEXT
already delivers the dedupe this phase can honestly claim: case.

**`uq_users_email` is partial, and nothing sets `deleted_at`.**  The predicate is
built as Part 4.2 declares it, but `account_repository.tombstone_user` still frees
a deleted account's address the way it always has -- by rewriting it to
`deleted-{id}@{tombstone_domain}` -- and never sets `deleted_at`.  So the index
behaves exactly like the full unique constraint it replaces.  The partial
semantics activate when soft-delete is actually adopted, which is a deletion-policy
change and not a schema one.

**`confirmation_token`, `confirmation_sent_at`, `reset_token` and `reset_sent_at`
are carried forward unchanged.**  Part 4.2 omits all four because its identity
design assumes a `user_sessions` table and a separate token store, neither of
which exists yet; all four are live today, behind `POST /auth/email/verify` and
the password-reset OTP.  Dropping a live column because the target diagram does
not draw it would be deleting a feature by omission.  They move to the token
table when that table lands.

Revision ID: 20260827_users_table
Revises: 20260827_profile_tables
Create Date: 2026-08-27
"""

