#: Already created by 20260827_profile_tables. Repeated because this migration
#: attaches a trigger that calls it, and a migration whose prerequisite is
#: "some earlier file happened to define this" is one that cannot be read alone.
#: `CREATE OR REPLACE` makes the repetition free.
_SET_UPDATED_AT = """
CREATE OR REPLACE FUNCTION solverah_set_updated_at() RETURNS trigger AS $BODY$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$BODY$ LANGUAGE plpgsql;
"""

_ROLES = ("job-seeker", "recruiter", "admin")
_STATUSES = ("pending", "active", "suspended", "deleted")


def upgrade():
    bind = op.get_bind()

    # citext is declared in infra/docker/initdb/01-extensions.sql and created as
    # a CI step; asserted here so a database missing it fails on the migration
    # rather than on the first login.
    op.execute("CREATE EXTENSION IF NOT EXISTS citext")

    # ---------------------------------------------------------------- rename
    # Postgres carries foreign keys through a table rename -- the twelve
    # constraints pointing at `user.id`, including Phase 2a's four, follow
    # automatically and are verified by tests/test_users_table.py. It does *not*
    # rename the sequence, the indexes, or the constraints, so anything still
    # carrying the old name is renamed below or replaced outright. A name left
    # alone here keeps `user_` forever.
    op.execute('ALTER TABLE "user" RENAME TO users')
    op.execute("ALTER INDEX user_pkey RENAME TO users_pkey")
    op.execute("ALTER INDEX ix_user_confirmation_token RENAME TO ix_users_confirmation_token")

    # ------------------------------------------------- internal column names
    # Both are internal: neither appears in any request or response.
    op.alter_column("users", "password", new_column_name="password_hash")
    op.alter_column("users", "failed_login_attempts", new_column_name="failed_login_count")

    # ------------------------------------------------------------ id -> bigint
    # SERIAL is a default plus an owned sequence. Identity is a property of the
    # column, so the default and the sequence go, the type widens, and Postgres
    # creates `users_id_seq` itself -- which is also how the sequence ends up
    # correctly named without an explicit rename.
    op.execute("ALTER TABLE users ALTER COLUMN id DROP DEFAULT")
    op.execute("DROP SEQUENCE IF EXISTS user_id_seq")
    op.execute("ALTER TABLE users ALTER COLUMN id TYPE BIGINT")
    op.execute("ALTER TABLE users ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY")
    op.execute(
        "SELECT setval(pg_get_serial_sequence('users', 'id'), "
        "COALESCE((SELECT MAX(id) FROM users), 0) + 1, false)"
    )

    # --------------------------------------------------------- widened types
    op.execute("ALTER TABLE users ALTER COLUMN email TYPE CITEXT")
    op.execute("ALTER TABLE users ALTER COLUMN password_hash TYPE TEXT")
    op.execute("ALTER TABLE users ALTER COLUMN name TYPE TEXT")
    op.execute("ALTER TABLE users ALTER COLUMN failed_login_count TYPE SMALLINT")

    # The three existing instants are `timestamp without time zone` holding UTC
    # -- `solverah.domain.auth.utcnow()` is timezone-aware, so `locked_until >
    # utcnow()` in the login path compares a naive value against an aware one and
    # raises TypeError the moment a lockout is actually in force. `AT TIME ZONE
    # 'UTC'` reads the stored value as what the application meant by it.
    for column in ("confirmation_sent_at", "reset_sent_at", "locked_until"):
        op.execute(
            "ALTER TABLE users ALTER COLUMN %s TYPE TIMESTAMPTZ "
            "USING %s AT TIME ZONE 'UTC'" % (column, column)
        )

    # ------------------------------------------------------------ role, status
    role_enum = postgresql.ENUM(*_ROLES, name="user_role")
    role_enum.create(bind)
    status_enum = postgresql.ENUM(*_STATUSES, name="user_status")
    status_enum.create(bind)

    # `role` is nullable today and every code path that creates a user sets
    # 'job-seeker', so the only NULLs are rows seeded without one. Any *other*
    # value would fail the cast below, and that is deliberate: a value no code
    # can produce showing up here means an assumption is wrong, and the migration
    # should say so rather than quietly rewrite it.
    op.execute("UPDATE users SET role = 'job-seeker' WHERE role IS NULL")
    op.execute("ALTER TABLE users ALTER COLUMN role TYPE user_role USING role::user_role")
    op.execute("ALTER TABLE users ALTER COLUMN role SET DEFAULT 'job-seeker'")
    op.execute("ALTER TABLE users ALTER COLUMN role SET NOT NULL")

    op.add_column(
        "users",
        sa.Column("status", status_enum, nullable=False, server_default="pending"),
    )
    # Read while `email_confirmed` still exists. A confirmed account is an active
    # one; anything else has not finished registering.
    op.execute("UPDATE users SET status = 'active' WHERE email_confirmed")

    # ------------------------------------- email_confirmed -> _at (boolean -> instant)
    op.add_column("users", sa.Column("email_confirmed_at", sa.DateTime(timezone=True)))
    # The boolean never carried an instant, so there is no true confirmation time
    # to recover for an existing row. `now()` is the only defensible fill and it
    # is knowingly wrong in the past tense: it says "confirmed at the migration",
    # not "confirmed when it happened". Nothing reads the value -- the wire
    # publishes `email_confirmed_at IS NOT NULL` -- so the falsehood is bounded to
    # rows that predate this migration and to a column no response exposes.
    op.execute("UPDATE users SET email_confirmed_at = now() WHERE email_confirmed")
    op.drop_column("users", "email_confirmed")

    # ------------------------------------------------------------ new columns
    op.add_column(
        "users",
        sa.Column(
            "public_id",
            postgresql.UUID(as_uuid=True),
            nullable=False,
            server_default=sa.text("uuidv7()"),
        ),
    )
    op.add_column("users", sa.Column("version", sa.Integer(), nullable=False, server_default="0"))
    op.add_column("users", sa.Column("last_login_at", sa.DateTime(timezone=True)))
    op.add_column(
        "users",
        sa.Column(
            "created_at",
            sa.DateTime(timezone=True),
            nullable=False,
            server_default=sa.func.now(),
        ),
    )
    op.add_column(
        "users",
        sa.Column(
            "updated_at",
            sa.DateTime(timezone=True),
            nullable=False,
            server_default=sa.func.now(),
        ),
    )
    op.add_column("users", sa.Column("deleted_at", sa.DateTime(timezone=True)))

    # ---------------------------------------------------------------- indexes
    op.create_index("uq_users_public_id", "users", ["public_id"], unique=True)
    # Replaces `user_email_key`, which the rename left carrying the old name.
    # Dropped rather than renamed because the predicate is new.
    op.execute("ALTER TABLE users DROP CONSTRAINT user_email_key")
    op.create_index(
        "uq_users_email",
        "users",
        ["email"],
        unique=True,
        postgresql_where=sa.text("deleted_at IS NULL"),
    )
    op.create_index(
        "ix_users_status",
        "users",
        ["status"],
        postgresql_where=sa.text("deleted_at IS NULL"),
    )

    # ---------------------------------------------------------------- trigger
    # P1-8's fourth bullet, for this table. `updated_at` with only a
    # `server_default` is a second `created_at`.
    op.execute(_SET_UPDATED_AT)
    op.execute("DROP TRIGGER IF EXISTS trg_users_updated_at ON users")
    op.execute(
        "CREATE TRIGGER trg_users_updated_at BEFORE UPDATE ON users "
        "FOR EACH ROW EXECUTE FUNCTION solverah_set_updated_at()"
    )


